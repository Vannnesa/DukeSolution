/* Run retirement() for one case with stdout diverted into a temporary file and
   return the captured text (malloc'd, NUL-terminated), or NULL on failure. */
static char * captureCase(const Case * c) {
  retire_info working;
  retire_info retired;
  int saved;
  FILE * tmp;
  char * buf;
  long len;

  working.months = c->wMonths;
  working.contribution = c->wContrib;
  working.rate_of_return = c->wRate;
  retired.months = c->rMonths;
  retired.contribution = c->rContrib;
  retired.rate_of_return = c->rRate;

  fflush(stdout);
  saved = dup(fileno(stdout));
  tmp = tmpfile();
  if (saved < 0 || tmp == NULL) {
    if (saved >= 0) close(saved);
    if (tmp != NULL) fclose(tmp);
    return NULL;
  }
  if (dup2(fileno(tmp), fileno(stdout)) < 0) {
    close(saved);
    fclose(tmp);
    return NULL;
  }

  retirement(c->age, c->initial, working, retired);

  fflush(stdout);
  dup2(saved, fileno(stdout));
  close(saved);

  if (fseek(tmp, 0, SEEK_END) != 0) {
    fclose(tmp);
    return NULL;
  }
  len = ftell(tmp);
  if (len < 0) {
    fclose(tmp);
    return NULL;
  }
  rewind(tmp);
  buf = malloc((size_t)len + 1);
  if (buf == NULL) {
    fclose(tmp);
    return NULL;
  }
  if (len > 0 && fread(buf, 1, (size_t)len, tmp) != (size_t)len) {
    free(buf);
    fclose(tmp);
    return NULL;
  }
  buf[len] = '\0';
  fclose(tmp);
  return buf;
}

/* The monthly series the README describes, rebuilt independently. */
static char * referenceCase(const Case * c) {
  int total = c->wMonths + c->rMonths;
  size_t cap = (size_t)(total + 1) * 64;
  char * buf = malloc(cap);
  size_t p = 0;
  double balance = c->initial;
  int age = c->age;

  if (buf == NULL) {
    return NULL;
  }
  for (int i = 0; i < c->wMonths; i++) {
    p += (size_t)snprintf(buf + p, cap - p, "Age %3d month %2d you have $%.2lf\n",
                          age / 12, age % 12, balance);
    balance = (balance * c->wRate) + c->wContrib + balance;
    age++;
  }
  for (int i = 0; i < c->rMonths; i++) {
    p += (size_t)snprintf(buf + p, cap - p, "Age %3d month %2d you have $%.2lf\n",
                          age / 12, age % 12, balance);
    balance = (balance * c->rRate) + c->rContrib + balance;
    age++;
  }
  return buf;
}

int main(void) {
  int failed = 0;

  /* The two header lines, byte for byte, including the trailing blanks of the
     first one. */
  printf("                |         Working              |        Retired         \n");
  printf(" Age | Initial  | Saving  |   Rate    | Months | Spending |   Rate    | Months | Result\n");

  for (int i = 0; i < NCASES; i++) {
    const Case * c = &cases[i];
    char * got = captureCase(c);
    char * want = referenceCase(c);
    int ok = (got != NULL) && (want != NULL) && (strcmp(got, want) == 0);

    printf(" %3d | %8.2f | %7.2f | %9.7f | %5d  | %8.2f | %9.7f | %5d  | %s\n",
           c->age, c->initial, c->wContrib, c->wRate, c->wMonths,
           c->rContrib, c->rRate, c->rMonths, ok ? "Correct" : "Incorrect");
    if (!ok) {
      failed++;
    }
    free(got);
    free(want);
  }
  return failed ? 1 : 0;
}
